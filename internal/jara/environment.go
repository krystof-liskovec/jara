package jara

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

func environment(args []string) error {
	f := flag.NewFlagSet("environment", flag.ContinueOnError)
	out := f.String("out", "jara-environment.env", "output env file")
	codex := f.String("codex-version", "", "exact Codex npm version; default: latest stable")
	node := f.String("node-version", "22.22.0", "Node image version")
	goVersion := f.String("go-version", "", "optional Go toolchain version")
	vim := f.Bool("vim", false, "install Vim")
	nvim := f.Bool("nvim", false, "install Neovim")
	glab := f.String("glab-version", "", "optional pinned GitLab CLI version")
	tea := f.String("tea-version", "", "optional pinned Gitea Tea version")
	docker := f.Bool("docker", false, "enable rootless Docker sidecar (also include compose.docker.yaml)")
	dockerVersion := f.String("docker-version", "29.9.2", "pinned Docker CLI and daemon version")
	mise := f.String("mise-version", "2026.10.24", "pinned project toolchain manager version")
	if err := f.Parse(args); err != nil {
		return err
	}
	if f.NArg() != 0 {
		return fmt.Errorf("unexpected environment argument")
	}
	semver := regexp.MustCompile(`^[0-9]+\.[0-9]+\.[0-9]+$`)
	if !semver.MatchString(*node) || (*goVersion != "" && !semver.MatchString(*goVersion)) {
		return fmt.Errorf("supply exact x.y.z versions")
	}
	if *codex == "" {
		version, err := latestCodex()
		if err != nil {
			return fmt.Errorf("resolve latest Codex version (or pass --codex-version to pin one): %w", err)
		}
		*codex = version
		fmt.Fprintf(os.Stderr, "Using latest Codex version %s\n", version)
	}
	if _, err := parseRelease(*codex); err != nil {
		return fmt.Errorf("Codex version: %w", err)
	}
	for _, v := range []string{*glab, *tea, *mise, *dockerVersion} {
		if v != "" && !semver.MatchString(v) {
			return fmt.Errorf("tool versions must be exact x.y.z versions")
		}
	}
	packages := ""
	if *vim {
		packages += " vim"
	}
	if *nvim {
		packages += " neovim"
	}
	body := fmt.Sprintf("# Generated by jara environment; use docker compose --env-file %s\nCODEX_VERSION=%s\nNODE_VERSION=%s\nGO_VERSION=%s\nEDITOR_PACKAGES=%s\nJARA_SSH_BIND=127.0.0.1\nJARA_SSH_PORT=2222\nJARA_GATEWAY_PORTS=no\n", filepath.Base(*out), *codex, *node, *goVersion, packages)
	body += fmt.Sprintf("GLAB_VERSION=%s\nTEA_VERSION=%s\n", *glab, *tea)
	body += fmt.Sprintf("MISE_VERSION=%s\n", *mise)
	body += fmt.Sprintf("DOCKER_VERSION=%s\n", *dockerVersion)
	if *docker {
		body += "JARA_DOCKER=1\n# Include -f deploy/compose.docker.yaml when deploying and updating.\n"
	} else {
		body += "JARA_DOCKER=0\n"
	}
	file, err := os.OpenFile(*out, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return fmt.Errorf("create configuration (existing files are preserved): %w", err)
	}
	_, err = file.WriteString(body)
	if e := file.Close(); err == nil {
		err = e
	}
	return err
}
